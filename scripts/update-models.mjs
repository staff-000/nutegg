import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compactModels, getEquivalentModels, getModels, ProviderId } from 'byokit';
import catalog from 'byokit/catalog';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const config = JSON.parse(await readFile(join(root, 'shared/byok.config.json'), 'utf8'));

// Discovery and compaction happen only here; consumers import byokit/client.
const direct = getModels(config);
for (const provider of config.providerIds.values) {
  if (!direct.some(model => model.providerId === provider))
    throw new Error(`No models for ${provider}; review shared/byok.config.json before updating the catalog.`);
}
const router = direct.flatMap(seed => getEquivalentModels([seed], {
  ...config, providerIds: [ProviderId.OpenRouter], dedupe: false, limit: 1,
}));
if (!router.length) throw new Error('No OpenRouter offerings match the selected models.');

const models = compactModels([...direct, ...router]);
const local = getModels({ providerIds: [ProviderId.Local] });
const providers = [...new Map([...local, ...direct, ...router].map(model => {
  if (!model.provider?.name || !model.connection)
    throw new Error(`Missing provider metadata for ${model.providerId}.`);
  return [model.providerId, { id: model.providerId, label: model.provider.name, connection: model.connection }];
})).values()];
const version = JSON.parse(await readFile(join(root, 'node_modules/byokit/package.json'), 'utf8')).version;
const header = '// Generated by npm run models:update from shared/byok.config.json; do not edit.\n';
await writeFile(join(root, 'shared/src/generated-models.mjs'),
  header + `export const GENERATED_PROVIDERS = ${JSON.stringify(providers, null, 2)};\n\n` +
  `export const GENERATED_MODELS = ${JSON.stringify(models, null, 2)};\n`);
await writeFile(join(root, 'shared/src/generated-models.d.mts'), header +
  "import type { Connection, ExecutionModel } from 'byokit/client';\n\n" +
  `export declare const GENERATED_PROVIDERS: readonly {\n  id: ${providers.map(provider => JSON.stringify(provider.id)).join(' | ')};\n  label: string;\n  connection: Connection;\n}[];\n` +
  'export declare const GENERATED_MODELS: readonly ExecutionModel[];\n');
const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
await writeFile(join(root, 'shared/models.lock.json'), JSON.stringify({
  byokitVersion: version,
  target: 'compact',
  asOf: config.asOf,
  configHash: hash(config),
  upstreamHash: hash(catalog),
  outputHash: hash({ providers, models }),
  direct: direct.map(model => model.id),
  openrouter: router.map(model => model.id),
}, null, 2) + '\n');
console.log(`Generated ${direct.length} direct and ${router.length} OpenRouter offerings (compact).`);
