import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const config = JSON.parse(await readFile(join(root, 'shared/byok.config.json'), 'utf8'));
const directory = await mkdtemp(join(tmpdir(), 'nutegg-models-'));

// BYOKit compiles the query offline. Ship selected native offerings unchanged;
// runtime execution imports byokit/client without the bundled catalog.
async function compile(name, query) {
  const input = join(directory, `${name}.json`);
  const output = join(directory, `${name}.mjs`);
  await writeFile(input, JSON.stringify(query));
  execFileSync(process.execPath, [join(root, 'node_modules/byokit/bin.mjs'), 'build', input, '--out', output], {
    stdio: 'inherit',
  });
  const { models } = await import(pathToFileURL(output).href);
  const lock = JSON.parse(await readFile(`${output}.lock.json`, 'utf8'));
  return { models, lock };
}

try {
  const direct = await compile('direct', config);
  for (const provider of config.providerIds.values) {
    if (!direct.models.some(model => model.providerId === provider))
      throw new Error(`No models for ${provider}; review shared/byok.config.json before updating the catalog.`);
  }
  // OpenRouter is the hosting provider, not the creator. Query its offerings
  // separately without a global dedupe cap, then join the selected canonical
  // model identities. Never construct reseller IDs by prefixing direct API IDs.
  const router = await compile('openrouter', { ...config, providerIds: ['openrouter'], dedupe: false });
  const selectedIds = new Set(direct.models.map(model => model.modelId));
  const seenIds = new Set();
  const routerModels = router.models.filter(model => {
    if (!selectedIds.has(model.modelId) || seenIds.has(model.modelId)) return false;
    seenIds.add(model.modelId);
    return true;
  });
  if (!routerModels.length) throw new Error('No OpenRouter offerings match the selected models.');
  const models = [...direct.models, ...routerModels];
  const local = await compile('local', { providerIds: ['local'] });
  const providers = [...new Map([...local.models, ...direct.models, ...routerModels].map(model => {
    if (!model.provider?.name || !model.connection)
      throw new Error(`Missing provider metadata for ${model.providerId}.`);
    return [model.providerId, { id: model.providerId, label: model.provider.name, connection: model.connection }];
  })).values()];
  const version = JSON.parse(await readFile(join(root, 'node_modules/byokit/package.json'), 'utf8')).version;
  const header = '// Generated by npm run models:update from shared/byok.config.json; do not edit.\n';
  await writeFile(join(root, 'shared/src/generated-models.ts'),
    header + `export const GENERATED_PROVIDERS = ${JSON.stringify(providers, null, 2)} as const;\n\n` +
    `export const GENERATED_MODELS = ${JSON.stringify(models, null, 2)} as unknown as import('byokit/client').ModelOption[];\n`);
  await writeFile(join(root, 'shared/models.lock.json'), JSON.stringify({
    byokitVersion: version,
    asOf: config.asOf,
    configHash: createHash('sha256').update(JSON.stringify(config)).digest('hex'),
    direct: direct.lock,
    openrouter: router.lock,
    local: local.lock,
  }, null, 2) + '\n');
  console.log(`Generated ${direct.models.length} direct and ${routerModels.length} OpenRouter offerings.`);
} finally {
  await rm(directory, { recursive: true, force: true });
}
