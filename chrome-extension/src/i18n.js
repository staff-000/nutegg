let currentLocale = "en";

/**
 * Determine effective language.
 */
function resolveLanguage(preferred) {
  if (preferred) {
    const p = preferred.toLowerCase();
    if (p === "zh" || p === "zh_cn" || p === "zh-cn") return "zh_CN";
    if (p === "en") return "en";
    if (p === "es") return "es";
    if (p === "ja") return "ja";
    if (p === "ko") return "ko";
    if (p === "ar") return "ar";
    if (p === "fr") return "fr";
    if (p === "de") return "de";
    if (p === "pt" || p === "pt_br" || p === "pt-br") return "pt";
    if (p === "ru") return "ru";
  }
  const browserLang = (
    (typeof chrome !== "undefined" && chrome?.i18n?.getUILanguage?.()) ||
    (typeof navigator !== "undefined" && navigator.language) ||
    "en"
  ).toLowerCase();

  if (browserLang.startsWith("zh")) return "zh_CN";
  if (browserLang.startsWith("es")) return "es";
  if (browserLang.startsWith("ja")) return "ja";
  if (browserLang.startsWith("ko")) return "ko";
  if (browserLang.startsWith("ar")) return "ar";
  if (browserLang.startsWith("fr")) return "fr";
  if (browserLang.startsWith("de")) return "de";
  if (browserLang.startsWith("pt")) return "pt";
  if (browserLang.startsWith("ru")) return "ru";
  return "en";
}

/**
 * Initialize i18n with user-configured UI language or auto-detected language.
 */
function initI18n(userPreference) {
  currentLocale = resolveLanguage(userPreference);
  return currentLocale;
}

